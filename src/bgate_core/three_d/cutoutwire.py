def game_fit(doc: dict, sizes: dict, player_height_px: int) -> dict:
    """How Visual is scaled and lifted so the DRAWN figure stands on the
    ground at its game height.

    Game height is the document's `game_height_px`, else the project's
    player height times `height_ratio`. The figure is measured from the
    parts (cutout.rest_extent), never taken from the template's nominal
    200 px. The lift puts the lowest drawn pixel on y = 0: a kit whose feet
    hang below the ankle bone otherwise sinks into the floor.

    Returns {scale, lift, figure_height_px, game_height_px, source}; scale 1
    with `source` saying why when there is no game height. The lift applies
    whenever the parts are measured: cutout.ground_clip solves every planted
    clip to the rest pose's lowest point, and this puts that point on y = 0.
    """
    doc = cutout.normalise(doc)
    want = int(doc.get("game_height_px") or 0)
    source = "game_height_px"
    if not want and player_height_px:
        want = int(round(int(player_height_px) * float(doc.get("height_ratio") or 1.0)))
        source = "player_height_px x height_ratio"
    extent = cutout.rest_extent(doc, sizes or {})
    if not want or not extent or extent["height"] <= 0:
        return {"scale": 1.0,
                "lift": round(-extent["bottom"], 3) if extent else 0.0,
                "figure_height_px": round(extent["height"], 1) if extent else 0.0,
                "game_height_px": want,
                "source": ("no game height: scale_contract_set(player_height_px"
                           "=...) or the rig's game_height_px"
                           if not want else "no part sizes to measure")}
    scale = want / extent["height"]
    return {"scale": round(scale, 4), "lift": round(-extent["bottom"] * scale, 3),
            "figure_height_px": round(extent["height"], 1),
            "game_height_px": want, "source": source}


def scene_text(doc: dict, *, project_dir: str | os.PathLike[str],
               library_res: str, script_res: str,
               sizes: Optional[dict] = None,
               fit: Optional[dict] = None) -> str:
    """The .tscn: bones as Node2Ds, filled slots as Sprite2Ds, one player.

    `sizes` maps slot -> (width, height) in pixels. Without it a sprite gets
    `centered = false` and NO offset, which puts the part's top-left on the
    joint — visibly wrong, but wrong in a way you can see and fix, which beats
    guessing a pivot offset from a size nobody measured.
    """
    doc = cutout.normalise(doc)
    rest = cutout.rest_pose(doc)
    sizes = sizes or {}
    skin = doc["skin"]

    textures = {}
    for slot, entry in skin.items():
        textures.setdefault(_res_path(project_dir, entry["texture"]), None)
    ext = {}
    lines_ext = []
    ident = 1
    lines_ext.append(
        f"[ext_resource type=\"Script\" uid=\"\" path=\"{script_res}\" id=\"1_rig\"]"
        .replace(" uid=\"\"", ""))
    lines_ext.append(
        f"[ext_resource type=\"AnimationLibrary\" path=\"{library_res}\" "
        f"id=\"2_lib\"]")
    for path in sorted(textures):
        ident += 1
        key = f"{ident + 1}_tex{ident}"
        ext[path] = key
        lines_ext.append(
            f"[ext_resource type=\"Texture2D\" path=\"{path}\" id=\"{key}\"]")

    body: list[str] = []
    body.append(f"[node name=\"{doc['name']}\" type=\"Node2D\"]")
    body.append("script = ExtResource(\"1_rig\")")
    # THE PIVOT TABLE TRAVELS WITH THE SCENE. equip() has to know where an
    # incoming texture hangs from, and baking one offset into the Sprite2D would
    # land every swapped part on the PREVIOUS part's pivot — the central feature
    # of a cutout rig, silently broken.
    pivots = {}
    for slot, entry in skin.items():
        pivots[_res_path(project_dir, entry["texture"])] = entry["pivot"]
    if pivots:
        body.append("part_pivots = {")
        body.append(",\n".join(f"\"{p}\": {_vec2([v[0], v[1]])}"
                               for p, v in sorted(pivots.items())))
        body.append("}")
    # AND THE TEXTURES ARE LISTED AS RESOURCES. Godot's exporter cannot see a
    # load() of a string built at runtime, so equipment textures referenced only
    # by path are stripped from an exported game and every swap fails there and
    # only there.
    if ext:
        body.append("equip_textures = [" + ", ".join(
            f"ExtResource(\"{key}\")" for _, key in sorted(ext.items())) + "]")
    body.append("")
    body.append("[node name=\"Visual\" type=\"Node2D\" parent=\".\"]")
    # GAME SCALE LIVES HERE, not on the instance. exit-67-r2 instanced the
    # rig at 0.64 (128 / the template's 200) over a figure that measured 212
    # with its boots 44 px under the floor. cutout_rig.gd flips Visual by
    # sign only, so this magnitude survives facing.
    if fit and abs(float(fit.get("lift") or 0.0)) > 1e-6:
        body.append(f"position = {_vec2([0.0, fit['lift']])}")
    if fit and abs(float(fit.get("scale") or 1.0) - 1.0) > 1e-6:
        body.append(f"scale = {_vec2([fit['scale'], fit['scale']])}")
    body.append("")

    # Bones, parents before children, so the .tscn's parent paths always exist.
    for bone in _hierarchy_order(doc):
        parent_path = _parent_path(doc, bone["name"])
        pos = to_godot_pos(rest[bone["name"]]["pos"])
        body.append(f"[node name=\"{bone['name']}\" type=\"Node2D\" "
                    f"parent=\"{parent_path}\"]")
        body.append(f"position = {_vec2(pos)}")
        rot = to_godot_rot(rest[bone["name"]]["rot"])
        if abs(rot) > 1e-9:
            body.append(f"rotation = {_f(rot)}")
        body.append("")

    for slot in doc["slots"]:
        entry = skin.get(slot["name"])
        if not entry:
            continue                      # an unfilled slot emits no node
        res = _res_path(project_dir, entry["texture"])
        bone_path = cutout.bone_node_path(doc, slot["bone"])
        body.append(f"[node name=\"{slot['name']}\" type=\"Sprite2D\" "
                    f"parent=\"{bone_path}\"]")
        body.append(f"texture = ExtResource(\"{ext[res]}\")")
        body.append("centered = false")
        size = sizes.get(slot["name"])
        if size:
            body.append("offset = " + _vec2([
                round(-entry["pivot"][0] * float(size[0]), 3),
                round(-(1.0 - entry["pivot"][1]) * float(size[1]), 3)]))
        body.append(f"z_index = {slot['z']}")
        # See the module note: Godot 4 z is parent-relative by default and a
        # flat table would sum down the chain.
        body.append("z_as_relative = false")
        if abs(entry["rot_offset"]) > 1e-9:
            body.append(f"rotation = {_f(to_godot_rot(entry['rot_offset']))}")
        if abs(entry["scale"] - 1.0) > 1e-9:
            body.append(f"scale = {_vec2([entry['scale'], entry['scale']])}")
        if entry.get("far_tint"):
            tint = entry["far_tint"]
            body.append("modulate = Color(%s)" % ", ".join(_f(c) for c in tint))
        body.append("")

    body.append("[node name=\"AnimationPlayer\" type=\"AnimationPlayer\" "
                "parent=\".\"]")
    body.append("libraries = {")
    body.append("\"\": ExtResource(\"2_lib\")")
    body.append("}")
    # Immediate, not deferred: see the module note on hitbox timing.
    body.append("callback_mode_method = 1")
    body.append("")

    steps = len(lines_ext) + 1
    head = [f"[gd_scene load_steps={steps} format=3]", ""]
    return "\n".join(head + lines_ext + [""] +
                     [HEADER % f"{doc['name']}{cutout.SUFFIX}"] + body) + "\n"


def _hierarchy_order(doc: dict) -> list[dict]:
    """Bones with every parent before its children."""
    out, placed = [], set()
    remaining = list(doc["bones"])
    while remaining:
        progressed = False
        for bone in list(remaining):
            parent = bone["parent"]
            if not parent or parent in placed:
                out.append(bone)
                placed.add(bone["name"])
                remaining.remove(bone)
                progressed = True
        if not progressed:                # normalise() refuses cycles first
            raise CutoutError("bone hierarchy could not be ordered")
    return out


def _parent_path(doc: dict, bone: str) -> str:
    by_name = {b["name"]: b for b in doc["bones"]}
    parent = by_name[bone]["parent"]
    if not parent:
        return "Visual"
    return cutout.bone_node_path(doc, parent)


# ---------------------------------------------------------------------------
# Emitting to disk, without stepping on a human
# ---------------------------------------------------------------------------

def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def stamp_path(scene_path: str | os.PathLike[str]) -> Path:
    return Path(str(scene_path) + STAMP_SUFFIX)


def emit(doc: dict, *, project_dir: str | os.PathLike[str],
         scene_path: str | os.PathLike[str],
         script_res: str = "res://addons/bgate/cutout_rig.gd",
         clips: Optional[list] = None, sizes: Optional[dict] = None,
         player_height_px: int = 0, force: bool = False) -> dict:
    """Write the scene and the library. Returns what it wrote and what it refused.

    BYTE-IDENTICAL FOR AN UNCHANGED DOCUMENT — of the emitter's own output. Godot
    rewrites uids and .import sidecars on disk when it opens the project, so the
    claim is scoped to the text this function produces and no further.
    """
    doc = cutout.normalise(doc)
    scene = Path(scene_path)
    library = scene.with_suffix("").with_suffix(".anims.tres")
    library_res = _res_path(project_dir, library)

    text_lib = library_text(doc, clips, sizes)
    fit = game_fit(doc, sizes or {}, player_height_px)
    text_scene = scene_text(doc, project_dir=project_dir,
                            library_res=library_res, script_res=script_res,
                            sizes=sizes, fit=fit)

    # A HUMAN'S EDITS ARE NOT OURS TO DISCARD. The stamp records what we last
    # wrote; a file on disk that no longer matches it was changed by someone,
    # and Godot itself changes scenes just by opening them.
    stamp = stamp_path(scene)
    previous = {}
    if stamp.is_file():
        try:
            previous = json.loads(stamp.read_text(encoding="utf-8"))
        except ValueError:
            previous = {}
    refused = []
    for path, text, key in ((scene, text_scene, "scene"),
                            (library, text_lib, "library")):
        if path.is_file() and previous.get(key) and not force:
            now = _digest(path.read_text(encoding="utf-8"))
            if now != previous[key]:
                refused.append({
                    "path": str(path), "kind": key,
                    "note": "this file has changed since the emitter last wrote "
                            "it — someone edited it, or Godot rewrote it on "
                            "open. Re-emit with force=True to discard those "
                            "changes."})
    if refused:
        return {"ok": False, "refused": refused, "scene": str(scene),
                "library": str(library)}

    scene.parent.mkdir(parents=True, exist_ok=True)
    scene.write_text(text_scene, encoding="utf-8")
    library.write_text(text_lib, encoding="utf-8")
    stamp.write_text(json.dumps({"scene": _digest(text_scene),
                                 "library": _digest(text_lib),
                                 "name": doc["name"],
                                 "template": doc["template"],
                                 "game_fit": fit}, indent=2),
                     encoding="utf-8")
    return {
        "ok": True,
        "scene": str(scene),
        "library": str(library),
        "scene_res": _res_path(project_dir, scene),
        "library_res": library_res,
        "clips": list(clips or cutout.clip_names()),
        "bones": len(doc["bones"]),
        "sprites": len(doc["skin"]),
        "unfilled": [s["name"] for s in doc["slots"] if s["name"] not in doc["skin"]],
        "game_fit": fit,
        "bytes": {"scene": len(text_scene), "library": len(text_lib)},
    }


def instance_overrides(project_dir: str | os.PathLike[str],
                       scene_path: str | os.PathLike[str]) -> list[dict]:
    """Game scenes that instance this rig AND scale it themselves.

    The emitter owns the rig's game size (Visual's scale); an instance with
    its own `scale` multiplies it. exit-67-r2's player.tscn carried 0.64 -
    an agent's guess at 128/200 - and would have shrunk a correctly sized
    rig to 82 px. Reported, never rewritten: the scene is the game's.
    """
    import re
    project = Path(project_dir)
    res = _res_path(project, scene_path)
    found = []
    for tscn in project.rglob("*.tscn"):
        parts = set(tscn.relative_to(project).parts)
        # A gym or a proof scales rigs up to look at them; that is not the game.
        if (".godot" in parts or "proof" in parts or "gym" in tscn.stem
                or tscn.resolve() == Path(scene_path).resolve()):
            continue
        try:
            text = tscn.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if res not in text:
            continue
        ids = re.findall(r'\[ext_resource[^\]]*path="' + re.escape(res)
                         + r'"[^\]]*id="([^"]+)"', text)
        for ident in ids:
            for m in re.finditer(r'\[node name="([^"]+)"[^\]]*instance=ExtResource\("'
                                 + re.escape(ident) + r'"\)\]([^\[]*)', text):
                scale = re.search(r"^scale = (Vector2\([^)]*\))", m.group(2), re.M)
                if scale:
                    found.append({"scene": _res_path(project, tscn),
                                  "node": m.group(1), "scale": scale.group(1),
                                  "note": "this instance scales a rig that is "
                                          "already game-sized; remove its "
                                          "scale line"})
    return found
